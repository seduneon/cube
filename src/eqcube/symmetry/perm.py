"""Permutations and finite permutation groups.

Conventions
-----------
- ``g.arr[i]`` is the image of point ``i`` under ``g``.
- Composition: ``(g * h)(i) == g(h(i))`` -- apply ``h`` first, then ``g``.
- ``Perm`` is immutable and hashable.
"""

from __future__ import annotations

from collections import deque
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from functools import cached_property


@dataclass(frozen=True, slots=True)
class Perm:
    """A permutation of the points ``0 .. n-1``."""

    arr: tuple[int, ...]

    def __post_init__(self) -> None:
        n = len(self.arr)
        if sorted(self.arr) != list(range(n)):
            raise ValueError(f"not a permutation of 0..{n - 1}: {self.arr}")

    # ── constructors ──────────────────────────────────────────────────────

    @classmethod
    def identity(cls, n: int) -> Perm:
        return cls(tuple(range(n)))

    @classmethod
    def from_cycles(cls, cycles: Iterable[Sequence[int]], n: int) -> Perm:
        """Cycle ``(a, b, c)`` means a -> b -> c -> a."""
        arr = list(range(n))
        for cycle in cycles:
            for k, point in enumerate(cycle):
                arr[point] = cycle[(k + 1) % len(cycle)]
        return cls(tuple(arr))

    # ── group structure ───────────────────────────────────────────────────

    @property
    def degree(self) -> int:
        return len(self.arr)

    def __call__(self, i: int) -> int:
        return self.arr[i]

    def __mul__(self, other: Perm) -> Perm:
        """``(self * other)(i) == self(other(i))``."""
        if self.degree != other.degree:
            raise ValueError(f"degree mismatch: {self.degree} vs {other.degree}")
        return Perm(tuple(self.arr[j] for j in other.arr))

    def inverse(self) -> Perm:
        inv = [0] * self.degree
        for i, j in enumerate(self.arr):
            inv[j] = i
        return Perm(tuple(inv))

    def is_identity(self) -> bool:
        return self.arr == tuple(range(self.degree))

    def order(self) -> int:
        """Smallest k >= 1 with self**k == identity."""
        p, k = self, 1
        while not p.is_identity():
            p, k = p * self, k + 1
        return k


class PermGroup:
    """The group generated by a set of permutations of equal degree."""

    def __init__(self, generators: Iterable[Perm]) -> None:
        gens = tuple(generators)
        if not gens:
            raise ValueError("need at least one generator")
        if len({g.degree for g in gens}) != 1:
            raise ValueError("all generators must have the same degree")
        self._generators = gens

    @property
    def generators(self) -> tuple[Perm, ...]:
        return self._generators

    @property
    def degree(self) -> int:
        return self._generators[0].degree

    @property
    def identity(self) -> Perm:
        return Perm.identity(self.degree)

    @cached_property
    def elements(self) -> frozenset[Perm]:
        """All group elements, computed once on first access (closure BFS).

        Generators alone suffice (no inverses needed): in a finite group every
        g has finite order k, so g^{-1} = g^{k-1} is a product of generators.
        """
        seen = {self.identity}
        queue = deque(seen)
        while queue:
            g = queue.popleft()
            for s in self._generators:
                h = s * g
                if h not in seen:
                    seen.add(h)
                    queue.append(h)
        return frozenset(seen)

    @property
    def order(self) -> int:
        return len(self.elements)

    def __contains__(self, g: Perm) -> bool:
        return g in self.elements

    def orbit(self, i: int) -> frozenset[int]:
        """{g(i) for g in G}, by BFS over generators.

        Touches only orbit points, never the (possibly huge) element list.
        """
        seen = {i}
        queue = deque(seen)
        while queue:
            j = queue.popleft()
            for s in self._generators:
                k = s(j)
                if k not in seen:
                    seen.add(k)
                    queue.append(k)
        return frozenset(seen)

    def stabilizer(self, i: int) -> PermGroup:
        """Subgroup {g in G : g(i) == i}.

        Uses all stabilizing elements as generators: wasteful but correct.
        (Schreier's lemma would give a small generating set.)
        """
        return PermGroup(g for g in self.elements if g(i) == i)
